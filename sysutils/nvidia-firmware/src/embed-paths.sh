#!/bin/sh
#
# Turn the path of the directory of the data into a C header.
#
# usage: embed-paths.sh <header>
#
# The path of the directory of the pin table is a value of the caller: it
# comes from the prefix the package is built with.  It is not written into
# the text of a command of the compiler: a path that holds a quote or a
# semicolon would end the argument of the compiler and would be read as
# shell syntax.  The path is read from the environment instead (the
# Makefile puts it there under the name NF_DATA_PATH) and written into a
# header with the escaping that a C string needs, so that the compiler is
# given the path as data and never as text.
#
# A path that holds a character that a C string cannot hold is refused:
# the build stops instead of writing a header that is broken.

set -eu

out=${1:-}

if [ -z "${out}" ]; then
	echo "usage: embed-paths.sh <header>" >&2
	exit 1
fi

dir=${NF_DATA_PATH:-}

if [ -z "${dir}" ]; then
	echo "embed-paths.sh: the directory of the data is not set" >&2
	exit 1
fi

# A control character, a newline among them, has no place in a path and
# no place in a C string that is written on one line.
case "${dir}" in
*[[:cntrl:]]*)
	echo "embed-paths.sh: the directory of the data holds a character" \
	    "that a path does not hold" >&2
	exit 1
	;;
esac

# The two characters that a C string needs to be escaped: the backslash
# and the double quote.
escaped=$(printf '%s' "${dir}" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')

{
	echo "/*"
	echo " * Generated by embed-paths.sh.  Do not edit."
	echo " */"
	echo ""
	echo "#define NF_DATA_DIR \"${escaped}\""
} > "${out}.tmp"

mv "${out}.tmp" "${out}"

exit 0
