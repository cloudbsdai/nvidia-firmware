#!/bin/sh
#
# Turn the version of the program into a C header.
#
# usage: embed-version.sh <header>
#
# The version of the program is the version of the package: the port
# gives its own DISTVERSION to the build, so that the program and the
# package always carry the same version.
#
# The version is a value of the caller and it is not written into the
# text of a command of the compiler: a version that holds a quote or a
# semicolon would end the argument of the compiler and would be read as
# shell syntax.  The version is read from the environment instead (the
# Makefile puts it there under the name NF_VERSION) and written into a
# header with the escaping that a C string needs, so that the compiler
# is given the version as data and never as text.
#
# The version has the format of a date version: three numbers separated
# by dots, and the number of a release of the same day after them.  The
# parser of the program reads the same format, so a version that this
# script accepts is a version that the program can read.  A version of
# another format is refused: the build stops instead of writing a
# header that holds a version nobody can read.

set -eu

out=${1:-}

if [ -z "${out}" ]; then
	echo "usage: embed-version.sh <header>" >&2
	exit 1
fi

version=${NF_VERSION:-}

if [ -z "${version}" ]; then
	echo "embed-version.sh: the version of the program is not set" >&2
	exit 1
fi

# Is the version a date version?  Three numbers separated by dots, and
# the number of a release of the same day after them.
is_date_version() {
	_rest=$1
	_parts=0
	while [ -n "${_rest}" ]; do
		case "${_rest}" in
		*.*)
			_part=${_rest%%.*}
			_rest=${_rest#*.}
			;;
		*)
			_part=${_rest}
			_rest=
			;;
		esac
		_parts=$((_parts + 1))
		case "${_part}" in
		'' | *[!0-9]*)
			return 1
			;;
		esac
		if [ ${_parts} -gt 4 ]; then
			return 1
		fi
	done
	[ ${_parts} -ge 3 ]
}

if ! is_date_version "${version}"; then
	echo "embed-version.sh: the version of the program is not a date" \
	    "version: ${version}" >&2
	exit 1
fi

# The version holds digits and dots only, so it needs no escaping in a C
# string.
{
	printf '%s\n' "/*"
	printf '%s\n' " * Generated by embed-version.sh.  Do not edit."
	printf '%s\n' " */"
	printf '%s\n' ""
	printf '%s\n' "#define NF_VERSION \"${version}\""
} > "${out}.tmp"

mv "${out}.tmp" "${out}"

exit 0
